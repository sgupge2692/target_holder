"""
Prometheus メトリクス定義

使い方:
    from app.metrics import REQUEST_COUNT, REQUEST_LATENCY, record_request

FastAPI ミドルウェアから自動で記録されます。
/metrics エンドポイントで Prometheus 互換テキストを返します。
"""
from prometheus_client import (
    Counter,
    Histogram,
    Gauge,
    generate_latest,
    CONTENT_TYPE_LATEST,
    CollectorRegistry,
    REGISTRY,
)

# ── カウンター ────────────────────────────────────────────────────────────
REQUEST_COUNT = Counter(
    "http_requests_total",
    "Total HTTP requests",
    ["method", "endpoint", "status_code"],
)

ERROR_COUNT = Counter(
    "http_errors_total",
    "Total HTTP 5xx errors",
    ["endpoint"],
)

SIGNAL_GENERATED_COUNT = Counter(
    "signals_generated_total",
    "Total signals generated by ML pipeline",
    ["signal_type"],
)

EMAIL_SENT_COUNT = Counter(
    "emails_sent_total",
    "Total emails sent",
    ["email_type", "provider"],
)

EMAIL_ERROR_COUNT = Counter(
    "email_errors_total",
    "Total email send failures",
    ["email_type"],
)

# ── ヒストグラム ───────────────────────────────────────────────────────────
REQUEST_LATENCY = Histogram(
    "http_request_duration_seconds",
    "HTTP request latency",
    ["method", "endpoint"],
    buckets=[0.01, 0.05, 0.1, 0.25, 0.5, 1.0, 2.5, 5.0, 10.0],
)

# ── ゲージ ────────────────────────────────────────────────────────────────
ACTIVE_USERS_GAUGE = Gauge(
    "active_users_total",
    "Total registered users",
    ["plan"],
)

SIGNAL_ACCURACY_GAUGE = Gauge(
    "signal_accuracy_percent",
    "Signal prediction accuracy (30 days)",
    ["signal_type"],
)


def metrics_output() -> tuple[bytes, str]:
    """Prometheus テキスト形式でメトリクスを返す"""
    return generate_latest(REGISTRY), CONTENT_TYPE_LATEST
